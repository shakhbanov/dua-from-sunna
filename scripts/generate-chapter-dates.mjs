#!/usr/bin/env node
// Derive datePublished / dateModified for every chapter from git history.
//
// The date a chapter's source file was added is its publication date; the date
// it was last touched is its modification date. Nothing here is synthesised:
// a file git cannot date contributes no entry, and a chapter with no entry
// emits no date fields at all — an absent date is correct, a made-up one is not.
//
// Emits data/chapterDates.generated.ts, consumed by the Article schema and by
// the sitemap's per-URL <lastmod>. Runs before `vite build`.

import fs from 'node:fs';
import path from 'node:path';
import url from 'node:url';
import { execFileSync } from 'node:child_process';

const __dirname = path.dirname(url.fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, '..');

function git(args) {
  try {
    return execFileSync('git', args, { cwd: root, encoding: 'utf8' }).trim();
  } catch {
    return '';
  }
}

// Chapter id is encoded in the filename: data/chapters/003-*.ts → 3,
// data/quran/2001-surah-001-*.ts → 2001.
function chapterFiles() {
  const out = [];
  for (const dir of ['data/chapters', 'data/quran']) {
    const abs = path.join(root, dir);
    if (!fs.existsSync(abs)) continue;
    for (const name of fs.readdirSync(abs)) {
      const m = /^(\d+)-.*\.ts$/.exec(name);
      if (m) out.push({ id: Number(m[1]), file: `${dir}/${name}` });
    }
  }
  return out.sort((a, b) => a.id - b.id);
}

const files = chapterFiles();
if (files.length === 0) {
  console.error('✗ chapter dates: no chapter source files found.');
  process.exit(1);
}

const dates = {};
let undated = [];

for (const { id, file } of files) {
  // --follow keeps the trail across renames, so a re-slugged chapter keeps the
  // publication date it actually had.
  const added = git(['log', '--follow', '--diff-filter=A', '--format=%aI', '--', file])
    .split('\n')
    .filter(Boolean)
    .pop();
  const modified = git(['log', '-1', '--format=%aI', '--', file]);
  if (!added || !modified) {
    undated.push(file);
    continue;
  }
  dates[id] = { published: added, modified };
}

// A shallow clone silently dates nothing. Fail rather than ship a site whose
// dates quietly vanished — the CI checkout must use fetch-depth: 0.
if (undated.length > files.length * 0.1) {
  console.error(
    `✗ chapter dates: ${undated.length}/${files.length} files have no git history. ` +
      `Is this a shallow clone? Use actions/checkout with fetch-depth: 0.`
  );
  process.exit(1);
}

const banner = `// Generated by scripts/generate-chapter-dates.mjs — do not edit, do not commit.
//
// Publication and modification dates taken from git history of each chapter's
// source file. Chapters git cannot date are absent here on purpose.

export interface ChapterDates {
  published: string;
  modified: string;
}

export const CHAPTER_DATES: Record<number, ChapterDates> = {
`;

const body = Object.entries(dates)
  .map(([id, d]) => `  ${id}: { published: '${d.published}', modified: '${d.modified}' },`)
  .join('\n');

const outFile = path.join(root, 'data', 'chapterDates.generated.ts');
fs.writeFileSync(outFile, `${banner}${body}\n};\n`, 'utf8');

const distinct = new Set(Object.values(dates).map((d) => d.modified.slice(0, 10)));
console.log(
  `✓ data/chapterDates.generated.ts (${Object.keys(dates).length}/${files.length} chapters, ` +
    `${distinct.size} distinct modification dates${undated.length ? `, ${undated.length} undated` : ''})`
);
